// Builds src/data/generated/portals.json — the ways between the surface, separate areas and dungeons (ladders, trapdoors, holes) the plugin points at when
// the target is in another layer than the player. Source: the transport table of the Shortest Path plugin (Skretzo/shortest-path, BSD 2-Clause),
// pinned to one commit so the file is reproducible. It needs a network. Run: npm run build-portals.
//
// Only rows that cross layers are kept (src/domain/travel/portals.ts); the same ladder listed from four tiles becomes one row.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dedupePortals, parseTransports, toRow } from '../../src/domain/travel/portals.ts';

const COMMIT = '99735452c7c257d3fe5ae79970429cdce907d571';
const URL_TSV = `https://raw.githubusercontent.com/Skretzo/shortest-path/${COMMIT}/src/main/resources/transports/transports.tsv`;
const root = fileURLToPath(new URL('../..', import.meta.url));
const OUT = `${root}src/data/generated/portals.json`;

const res = await fetch(URL_TSV, { headers: { 'User-Agent': 'osrs-route-money-builder' }, signal: AbortSignal.timeout(30_000) });
if (!res.ok) throw new Error(`transports.tsv: HTTP ${res.status}`);
const { portals, floors, skipped } = parseTransports(await res.text());
// Areas the pinned table lacks, from Quest Helper's objects. shortcut: the arrival tile is the corner of Quest Helper's zone, not a
// measured tile; replace these rows when the transport table gains the area.
const AUTHORED: (number | string)[][] = [
  [3361, 3150, 0, 3361, 11482, 0, 44635, 'Enter Cave', ''], // Giants' Foundry (Sleeping Giants)
  [3361, 11482, 0, 3361, 3150, 0, 44636, 'Exit Cave', ''],
  [3059, 3590, 0, 2281, 4837, 0, 34742, 'Enter Mysterious ruins', ''], // Chaos altar, with a chaos talisman (What Lies Below)
  // shortcut: areas reached through other areas, so the row is the first entrance on the surface, not one step; replace when the arrow follows chains.
  [3209, 3216, 0, 2512, 5564, 0, 14880, 'Climb-down Trapdoor', ''], // Dorgesh-Kaan railway dig (cellar, mines, city, train; Another Slice of H.A.M.)
  [3169, 3172, 0, 2404, 5540, 0, 5947, 'Climb-down Dark hole', ''], // H.A.M. storerooms (swamp caves, then the H.A.M. ladder)
];
const rows = [...dedupePortals(portals).map(toRow), ...AUTHORED];
const floorRows = dedupePortals(floors).map(toRow);
const file = {
  source: `Skretzo/shortest-path, src/main/resources/transports/transports.tsv at ${COMMIT} (BSD 2-Clause, see THIRD_PARTY_NOTICES.md)`,
  note: 'Generated by scripts/data/build-portals.ts; do not edit by hand. Rows: [x, y, plane, toX, toY, toPlane, objectId, action, requirement]. portals cross layers (surface / separate area / dungeon); floors change the floor within a layer.',
  portals: rows,
  // Same layer, another floor: staircases and ladders (Arsen in the central hut is a floor up).
  floors: floorRows,
};
writeFileSync(OUT, `${JSON.stringify(file, null, 0).replace(/\],\[/g, '],\n[')}\n`);
console.log(`portals: ${rows.length} (from ${portals.length} cross-layer rows), floors: ${floorRows.length} (from ${floors.length}); ${skipped} rows unreadable`);
