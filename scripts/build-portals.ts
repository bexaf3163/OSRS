// Builds src/data/portals.json — the ways between the surface, separate areas and dungeons (ladders, trapdoors, holes) the plugin points at when
// the target is in another layer than the player. Source: the transport table of the Shortest Path plugin (Skretzo/shortest-path, BSD 2-Clause),
// pinned to one commit so the file is reproducible. It needs a network. Run: npm run build-portals.
//
// Only rows that cross layers are kept (src/lib/portals.ts); the same ladder listed from four tiles becomes one row.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dedupePortals, parseTransports, toRow } from '../src/lib/portals.ts';

const COMMIT = '99735452c7c257d3fe5ae79970429cdce907d571';
const URL_TSV = `https://raw.githubusercontent.com/Skretzo/shortest-path/${COMMIT}/src/main/resources/transports/transports.tsv`;
const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = `${root}src/data/portals.json`;

const res = await fetch(URL_TSV, { headers: { 'User-Agent': 'OSRS-Path (https://github.com/bexaf3163/OSRS)' }, signal: AbortSignal.timeout(30_000) });
if (!res.ok) throw new Error(`transports.tsv: HTTP ${res.status}`);
const { portals, floors, skipped } = parseTransports(await res.text());
const rows = dedupePortals(portals).map(toRow);
const floorRows = dedupePortals(floors).map(toRow);
const file = {
  source: `Skretzo/shortest-path, src/main/resources/transports/transports.tsv at ${COMMIT} (BSD 2-Clause, see THIRD_PARTY_NOTICES.md)`,
  note: 'Generated by scripts/build-portals.ts; do not edit by hand. Rows: [x, y, plane, toX, toY, toPlane, objectId, action, requirement]. portals cross layers (surface / separate area / dungeon); floors change the floor within a layer.',
  portals: rows,
  // Same layer, another floor: staircases and ladders (Arsen in the central hut is a floor up).
  floors: floorRows,
};
writeFileSync(OUT, `${JSON.stringify(file, null, 0).replace(/\],\[/g, '],\n[')}\n`);
console.log(`portals: ${rows.length} (from ${portals.length} cross-layer rows), floors: ${floorRows.length} (from ${floors.length}); ${skipped} rows unreadable`);
